    private void productChanged() {

    String category = (String) jComboBox1.getSelectedItem();
    String product = (String) jComboBox2.getSelectedItem();

    if (category == null || product == null) {
        return;
    }

    if (category.equals("Snacks")) {

        if (product.equals("Piatos")) {
            jTextField1.setText("22.00");

        } else if (product.equals("Nova")) {
            jTextField1.setText("25.00");
        }

    } else if (category.equals("Drinks")) {

        if (product.equals("Coke")) {
            jTextField1.setText("20.00");

        } else if (product.equals("Sprite")) {
            jTextField1.setText("20.00");
        }
    }
}
    
   private void addOrder() {

    try {

        
        int quantity = Integer.parseInt(jTextField2.getText());

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "Quantity must be greater than 0."
            );
            return;
        }

    
        double price = Double.parseDouble(jTextField1.getText());

      
        subtotal = price * quantity;

       
        jTextField4.setText(
            String.format("%.2f", subtotal)
        );

        
        double cash = Double.parseDouble(jTextField3.getText());


       
        if (cash < subtotal) {

            JOptionPane.showMessageDialog(
                this,
                "Insufficient cash!"
            );

            jTextField3.setText("");

            addOrder();  

            return;
        }


        
        change = cash - subtotal;

        
        jTextField5.setText(
            String.format("%.2f", change)
        );

        JOptionPane.showMessageDialog(
            this,
            "Order added successfully!"
            + "\nProduct: " + jComboBox2.getSelectedItem()
            + "\nQuantity: " + quantity
            + "\nSubtotal: PHP "
            + String.format("%.2f", subtotal)
            + "\nCash: PHP "
            + String.format("%.2f", cash)
            + "\nChange: PHP "
            + String.format("%.2f", change)
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid number."
        );
    }
}
   
